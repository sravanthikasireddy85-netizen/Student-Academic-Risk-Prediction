"""Train and evaluate models on clearly labelled synthetic demonstration data."""
from pathlib import Path
import sys, json
import numpy as np, pandas as pd, joblib
from sklearn.model_selection import train_test_split, StratifiedKFold, cross_val_score
from sklearn.pipeline import Pipeline
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, confusion_matrix, classification_report
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier, ExtraTreesClassifier, HistGradientBoostingClassifier
from src.data_preprocessing import FEATURES, clean_features, make_preprocessor
ROOT=Path(__file__).resolve().parents[1]; DATA=ROOT/'data'/'raw'/'synthetic_students.csv'; MODELS=ROOT/'models'
LABELS=['LOW RISK','MEDIUM RISK','HIGH RISK']
def create_synthetic_dataset(n=600, seed=42):
    rng=np.random.default_rng(seed)
    attendance=rng.uniform(35,100,n); gpa=rng.uniform(3,10,n); internal=rng.uniform(20,100,n); assign=rng.uniform(20,100,n); backlogs=rng.poisson(1.1,n).clip(0,8); study=rng.uniform(0.2,8,n); fails=rng.poisson(.7,n).clip(0,6); participation=rng.uniform(15,100,n); submission=rng.uniform(20,100,n); subjects=rng.integers(4,9,n); pct=rng.uniform(25,100,n)
    # Synthetic target derived from a transparent score, not a real-world outcome.
    score=(attendance<65)*1.4+(gpa<5.5)*1.5+(internal<45)*1.0+(assign<55)*.8+(backlogs>1)*1.1+(study<1.5)*.6+(fails>1)*.8+(submission<55)*.5
    # Add noise to avoid a perfectly deterministic mapping; this is still demo-only.
    score=score+rng.normal(0,.65,n)
    risk=np.where(score>=3.4,2,np.where(score>=1.5,1,0))
    df=pd.DataFrame({'student_id':[f'DEMO{i+1:04d}' for i in range(n)],'student_name':[f'Demo Student {i+1:03d}' for i in range(n)],'age':rng.integers(17,27,n),'gender':rng.choice(['Female','Male','Prefer not to say'],n),'attendance_pct':attendance,'previous_gpa':gpa,'internal_marks_pct':internal,'assignment_completion_pct':assign,'backlogs':backlogs,'study_hours_per_day':study,'previous_failures':fails,'class_participation_pct':participation,'assignment_submission_rate':submission,'number_of_subjects':subjects,'previous_semester_pct':pct,'academic_risk':risk})
    return df

def train():
    MODELS.mkdir(exist_ok=True); DATA.parent.mkdir(parents=True,exist_ok=True)
    df=create_synthetic_dataset(); df.to_csv(DATA,index=False)
    X=clean_features(df); y=df['academic_risk']
    Xtr,Xte,ytr,yte=train_test_split(X,y,test_size=.25,random_state=42,stratify=y)
    models={'Logistic Regression':LogisticRegression(max_iter=1500,class_weight='balanced'),'Decision Tree':DecisionTreeClassifier(max_depth=7,class_weight='balanced',random_state=42),'Random Forest':RandomForestClassifier(n_estimators=180,min_samples_leaf=2,class_weight='balanced',random_state=42),'Extra Trees':ExtraTreesClassifier(n_estimators=180,min_samples_leaf=2,class_weight='balanced',random_state=42)}
    try:
        from xgboost import XGBClassifier
        models['XGBoost']=XGBClassifier(n_estimators=140,max_depth=4,learning_rate=.06,subsample=.9,colsample_bytree=.9,objective='multi:softprob',num_class=3,eval_metric='mlogloss',random_state=42,n_jobs=2)
    except Exception: pass
    results=[]; fitted={}; matrices={}; reports={}
    for name,model in models.items():
        pipe=Pipeline([('preprocessor',make_preprocessor()),('model',model)])
        try: pipe.fit(Xtr,ytr); pred=pipe.predict(Xte)
        except Exception as e:
            print(f'Skipping {name}: {e}'); continue
        row={'model':name,'accuracy':float(accuracy_score(yte,pred)),'precision':float(precision_score(yte,pred,average='weighted',zero_division=0)),'recall':float(recall_score(yte,pred,average='weighted',zero_division=0)),'f1':float(f1_score(yte,pred,average='weighted',zero_division=0))}
        results.append(row); fitted[name]=pipe; matrices[name]=confusion_matrix(yte,pred,labels=[0,1,2]).tolist(); reports[name]=classification_report(yte,pred,labels=[0,1,2],target_names=['LOW RISK','MEDIUM RISK','HIGH RISK'],zero_division=0)
    if not fitted: raise RuntimeError('No model trained successfully. Check installed dependencies.')
    # F1 first, recall as tie-breaker; do not select by accuracy alone.
    best=sorted(results,key=lambda r:(r['f1'],r['recall'],r['precision']),reverse=True)[0]
    joblib.dump(fitted[best['model']],MODELS/'best_model.pkl')
    meta={'best_model':best['model'],'metrics':results,'confusion_matrices':matrices,'classification_reports':reports,'labels':LABELS,'dataset':'Synthetic/demo data generated by this project; not real-world validated.'}
    (MODELS/'model_metadata.json').write_text(json.dumps(meta,indent=2),encoding='utf-8')
    joblib.dump({'features':FEATURES,'labels':LABELS},MODELS/'preprocessor.pkl')
    return meta
if __name__=='__main__':
    m=train(); print('Best model:',m['best_model']); print(json.dumps(m['metrics'],indent=2))
